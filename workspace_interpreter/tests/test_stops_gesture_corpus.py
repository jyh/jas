"""The stops-kind gesture corpus (test_fixtures/widget_events/stops_gestures.json).

GENERATED by running the reference over the shipped `grad_slider`; the
engine and Swift are held to it. This consumer checks that the golden is
what the reference produces now, and that it exercises every outcome, every
refusal and every gesture, so a generator that dropped a class of step
cannot stay green.
"""

import importlib.util
import json
import pathlib

from workspace_interpreter import widget_event as we

ROOT = pathlib.Path(__file__).resolve().parents[2]
GOLDEN = ROOT / "test_fixtures" / "widget_events" / "stops_gestures.json"
GENERATOR = ROOT / "scripts" / "gen_stops_gesture_corpus.py"


def _generator():
    spec = importlib.util.spec_from_file_location("gen_stops_gesture_corpus", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _golden():
    with GOLDEN.open(encoding="utf-8") as f:
        return json.load(f)


def _steps():
    return [s for c in _golden()["cases"] for s in c["steps"]]


def test_the_golden_is_fresh():
    gen = _generator()
    assert GOLDEN.read_text(encoding="utf-8") == gen.render(gen.build()), \
        "stale: run python scripts/gen_stops_gesture_corpus.py"


def test_every_outcome_refusal_and_gesture_is_exercised():
    steps = _steps()
    assert {s["expected"]["outcome"] for s in steps} == {"committed", "refused", "inert"}
    assert {s["expected"]["reason"] for s in steps} - {None} == {
        we.NO_PRESS, we.LAW_REFUSED, we.WRONG_EVENT}
    assert {s["gesture"] for s in steps} >= set(we.STOPS_GESTURES)


def test_a_commit_runs_the_shipped_behavior_and_a_drag_does_not():
    # The shipped YAML's one `commit` behavior writes gradient_stops; a drag
    # and a press write the panel only.
    for s in _steps():
        e = s["expected"]
        if s["gesture"] in ("press", "drag", "press_midpoint", "drag_midpoint"):
            assert e["behaviors_run"] == 0 and e["committed"] is None, s
        elif e["outcome"] == "committed":
            assert e["behaviors_run"] == 1 and e["committed"] == e["stops"], s
