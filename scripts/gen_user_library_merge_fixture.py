#!/usr/bin/env python3
"""Generate test_fixtures/algorithms/user_library_merge.json from the RULE.

At launch a host lays the user's saved libraries over the bundle's, slug for
slug, the user's winning (the Mac's `BrushLibraryStore.merged`). The saved
layout is the one every writer uses (Swift `BrushLibraryStore`, the Windows
shell's `PanelWire` write path):

    brushes/<slug>/library.json     brush_libraries
    swatches/<id>.json              swatch_libraries
    gradients/<id>.json             gradient_libraries

A file is read only when its whole text parses to a JSON OBJECT; anything
else (an array, malformed text, a wrong extension, the wrong layout for its
folder) is skipped, never an error. `rule` below states the law independent
of either port; Rust (`algorithm_user_library_merge_vectors`) and Swift
(`testAlgorithmUserLibraryMerge`) write each case's `files` into an empty
directory and run their loader over it. Re-run after editing a case:

    python3 scripts/gen_user_library_merge_fixture.py
"""
import json
from pathlib import Path

FIXTURE = Path(__file__).resolve().parent.parent / "test_fixtures" / "algorithms" / "user_library_merge.json"

LAYOUT = {"brush_libraries": "brushes", "swatch_libraries": "swatches", "gradient_libraries": "gradients"}


def parse_object(text):
    try:
        v = json.loads(text)
    except ValueError:
        return None
    return v if isinstance(v, dict) else None


def load(kind, files):
    """The user's libraries of one kind, from {relative path: text}."""
    folder = LAYOUT[kind]
    out = {}
    for path, text in sorted(files.items()):
        parts = path.split("/")
        if parts[0] != folder:
            continue
        if kind == "brush_libraries":
            ok = len(parts) == 3 and parts[2] == "library.json"
            slug = parts[1] if ok else None
        else:
            ok = len(parts) == 2 and parts[1].endswith(".json") and len(parts[1]) > 5
            slug = parts[1][:-5] if ok else None
        if ok and (lib := parse_object(text)) is not None:
            out[slug] = lib
    return out


def rule(bundle, files):
    return {kind: {**bundle.get(kind, {}), **load(kind, files)} for kind in LAYOUT}


def lib(name):
    return {"name": name}


BUNDLE = {
    "brush_libraries": {"acme": lib("Acme"), "basic": lib("Basic")},
    "swatch_libraries": {"web_colors": lib("Web Colors")},
    "gradient_libraries": {"neutrals": lib("Neutrals")},
}

CASES = [
    ("no_saved_files_keeps_the_bundle", {}),
    ("a_saved_brush_library_shadows_the_bundles_slug", {"brushes/acme/library.json": '{"name": "Acme (mine)"}'}),
    ("a_saved_brush_library_with_a_new_slug_is_added", {"brushes/mine/library.json": '{"name": "Mine"}'}),
    ("a_brush_folder_without_library_json_is_skipped", {"brushes/empty/notes.txt": "hello"}),
    ("a_flat_file_in_brushes_is_skipped", {"brushes/flat.json": '{"name": "Flat"}'}),
    ("a_json_array_is_skipped", {"brushes/arr/library.json": "[1, 2]"}),
    ("malformed_json_is_skipped", {"swatches/broken.json": '{"name": '}),
    ("a_saved_swatch_library_shadows_the_bundles_id", {"swatches/web_colors.json": '{"name": "Web (mine)"}'}),
    ("a_non_json_extension_in_swatches_is_skipped", {"swatches/notes.txt": '{"name": "Text"}'}),
    ("a_nested_file_in_swatches_is_skipped", {"swatches/deep/library.json": '{"name": "Deep"}'}),
    ("a_saved_gradient_library_is_added", {"gradients/sunset.json": '{"name": "Sunset"}'}),
    ("every_kind_at_once", {
        "brushes/acme/library.json": '{"name": "Acme (mine)"}',
        "brushes/zed/library.json": '{"name": "Zed"}',
        "swatches/pastels.json": '{"name": "Pastels"}',
        "gradients/neutrals.json": '{"name": "Neutrals (mine)"}',
        "gradients/bad.json": "nope",
    }),
]


def main():
    doc = json.loads(FIXTURE.read_text(encoding="utf-8")) if FIXTURE.exists() else {}
    doc = {"_doc": doc.get("_doc") or [
        "Laying a user's saved libraries over the bundle's at launch, slug for slug,",
        "the user's winning. Generated by scripts/gen_user_library_merge_fixture.py,",
        "whose docstring states the layout and the law; `rule` computes `expected`.",
        "",
        "Case: {name, files, expected}. `files` maps a path relative to the saved",
        "root to its exact text. The bundle is the shared `bundle` below. `expected`",
        "holds the merged libraries of all three kinds.",
    ], "bundle": BUNDLE}
    doc["cases"] = [{"name": n, "files": f, "expected": rule(BUNDLE, f)} for n, f in CASES]
    FIXTURE.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8", newline="")
    changed = sum(c["expected"] != rule(BUNDLE, {}) for c in doc["cases"])
    print(f"{len(doc['cases'])} cases, {changed} change the bundle")


if __name__ == "__main__":
    main()
